import re
import sys
import tomllib
import uuid

MOD = os.path.abspath(sys.argv[1])
DATA = os.path.join(MOD, "GameData")
GAMEPLAY = os.path.join(DATA, "Gameplay")
GENERATED = os.path.join(GAMEPLAY, "Gfx", "Generated")
UNIT_BASE = "Cromwell_V_POL"
WEAPON_BASE = "Stuart_M3A3_POL"

# Every number and text that a user may want to change lives in data/units.toml.
SETTINGS_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "units.toml")
with open(SETTINGS_PATH, "rb") as _handle:
    SETTINGS = tomllib.load(_handle)
VARIANTS = SETTINGS["units"]
AMMO = SETTINGS["ammo"]
# Order of the ammunition in each unit's weapon list (turret by turret, as in the Stuart layout).
AMMO_ORDER = {
    "TP7_JW_POL": ["Ammo_Bofors_wz37_AP", "Ammo_Bofors_wz37_HE", "Ammo_ckm_wz30_vehicule"],
    "TP7_DW_POL": ["Ammo_ckm_wz30_vehicule", "Ammo_ckm_wz30_vehicule"],
}


def salvos_of(unit, ammo):
    """Rounds from the settings turned into the game's salvo count."""
    rounds = VARIANTS[unit]["ammo"][ammo]
    per_salvo = AMMO[ammo]["rounds_per_salvo"]
    if rounds % per_salvo:
        print("note: %s %s: %d rounds is not a whole number of salvos of %d" % (unit, ammo, rounds, per_salvo))
    return max(1, round(rounds / per_salvo))
PACKS = [
    ("Descriptor_Deck_Pack_POL_7TP_JW_A", "TP7_JW_POL", 0, 1, 2, 3),
    ("Descriptor_Deck_Pack_POL_7TP_JW_B", "TP7_JW_POL", 1, 1, 3, 2),
    ("Descriptor_Deck_Pack_POL_7TP_DW_A", "TP7_DW_POL", 0, 0, 3, 2),
]
DIVISION = "Descriptor_Deck_Division_POL_Grupa_7TP_MULTI"
DIVISION_BASE = "Descriptor_Deck_Division_POL_1st_Armored_MULTI"
TEXTS = SETTINGS["texts"]
MARKER = "// 7TP mod: generated by create_battlegroup.py"


def path_of(*parts):
    return os.path.join(GAMEPLAY, *parts)


def read(path):
    with open(path, "rb") as handle:
        return handle.read().decode("latin-1")


def write(path, text):
    with open(path, "wb") as handle:
        handle.write(text.encode("latin-1"))


def new_guid(owner, old):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "7tp-steel-division/%s/%s" % (owner, old.lower())))


def fresh_guids(text, owner):
    return re.sub(r"GUID:\{([0-9a-fA-F-]+)\}", lambda m: "GUID:{%s}" % new_guid(owner, m.group(1)), text)


def skip(text, i):
    """Skip a comment or string starting at i, or return i unchanged."""
    if text.startswith("//", i):
        j = text.find("\n", i)
        return len(text) if j < 0 else j
    for opening, closing in (("/*", "*/"), ("(*", "*)")):
        if text.startswith(opening, i):
            j = text.find(closing, i + 2)
            return len(text) if j < 0 else j + 2
    if text[i] in "'\"":
        j = text.find(text[i], i + 1)
        return len(text) if j < 0 else j + 1
    return i


def matching(text, opening):
    """Index just after the bracket that closes the one at `opening`."""
    depth, i = 0, opening
    while i < len(text):
        after = skip(text, i)
        if after != i:
            i = after
            continue
        if text[i] in "([{":
            depth += 1
        elif text[i] in ")]}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError("Unbalanced brackets")


def statements(text):
    """Top-level `name is value` statements as (name, start, end)."""
    pattern = re.compile(r"(?:(?:export|private)\s+)?(\w+)\s+is\b")
    out, i = [], 0
    while i < len(text):
        after = skip(text, i)
        if after != i:
            i = after
            continue
        if text[i] in "([{":
            i = matching(text, i)
            continue
        if i == 0 or text[i - 1] in " \t\r\n)]":
            match = pattern.match(text, i)
            if match:
                j = match.end()
                while text[j] in " \t\r\n":
                    j += 1
                if text[j] in "'\"":
                    end = skip(text, j)
                else:
                    k = j
                    while text[k] not in "([{'\"\r\n":
                        k += 1
                    while text[k] in " \t\r\n":
                        k += 1
                    end = matching(text, k) if text[k] in "([{" else k
                out.append((match.group(1), match.start(), end))
                i = end
                continue
        i += 1
    return out


def get_object(text, name):
    for found, start, end in statements(text):
        if found == name:
            return text[start:end]
    raise KeyError(name)


def set_field(text, key, value):
    text, count = re.subn(r"(?m)^(\s*" + key + r"\s*=\s*).*?(\s*)$", lambda m: m.group(1) + str(value) + m.group(2), text)
    if not count:
        raise KeyError(key)
    return text


def append(path, blocks):
    if blocks:
        text = read(path)
        write(path, text.rstrip() + "\r\n\r\n" + MARKER + "\r\n" + "\r\n\r\n".join(blocks) + "\r\n")


def list_items(text, key):
    """Span and top-level items of `key = [ ... ]`."""
    match = re.search(key + r"\s*=\s*\[", text)
    opening = match.end() - 1
    closing = matching(text, opening)
    items, i, start = [], opening + 1, None
    while i < closing - 1:
        after = skip(text, i)
        if after != i:
            i = after
            continue
        if text[i] in "([{":
            end = matching(text, i)
            if start is not None:
                items.append(text[start:end])
                start = None
            i = end
            continue
        if text[i].isalpha() and start is None:
            start = i
        i += 1
    return opening, closing, items


def turret_text(turret, tag_number, weapon_number, salvo, effect, rotation):
    for key in ("AimingPriority", "MasterTurretIndex"):
        turret = re.sub(r"(?m)^\s*" + key + r"\s*=.*\r?\n", "", turret)
    # An independent turret needs its own targeting properties, as in the game's own tanks.
    turret = set_field(turret, "FlyingTimeAndHitPhysicalPropertyName", "'FlyingTimeAndHit%d'" % tag_number)
    turret = set_field(turret, "TargetPositionPhysicalPropertyName", "'TargetPositionTurret%d'" % tag_number)
    turret = set_field(turret, "AngleRotationMax", rotation)
    turret = set_field(turret, "Tag", "'tourelle%d'" % tag_number)
    turret = set_field(turret, "TagIndex", tag_number)
    turret = set_field(turret, "TagIndexForMissileStart", tag_number)
    turret = set_field(turret, "EffectTag", "'weapon_effet_tag%d'" % effect)
    turret = set_field(turret, "SalvoStockIndex", salvo)
    # The unit panel groups identical weapons: same interface slot, total number of barrels.
    turret = set_field(turret, "SalvoStockIndex_ForInterface", 0)
    return set_field(turret, "WeaponNumber_ForInterface", weapon_number)


def weapon_descriptor(source, name, variant):
    text = source.replace(WEAPON_BASE, name)
    opening, closing, turrets = list_items(text, "TurretDescriptorList")
    mg = turrets[1].replace("~/Ammo_M1919_7_62mm_vehicule", "~/Ammo_ckm_wz30_vehicule")
    # Ammunition stocks come from data/units.toml, in rounds; see salvos_of.
    salvos = [salvos_of(name, ammo) for ammo in AMMO_ORDER[name]]
    if variant == "jw":
        gun = turrets[0].replace("~/Ammo_Canon_M5_37mmL_AP", "~/Ammo_Bofors_wz37_AP").replace("~/Ammo_Canon_M5_37mmL_HE", "~/Ammo_Bofors_wz37_HE")
        kept = [gun, set_field(mg, "WeaponNumber_ForInterface", 1)]
    else:
        kept = [turret_text(mg, 1, 2, 0, 1, 2.09439510239), turret_text(mg, 2, 2, 1, 2, 2.09439510239)]
    text = text[:opening + 1] + "\r\n        " + ",\r\n        ".join(kept) + "\r\n    " + text[closing - 1:]
    salvos += [-1] * (29 - len(salvos))
    return re.sub(r"Salves\s*=\s*\[.*?\]", "Salves               = [ " + ", ".join(str(v) for v in salvos) + " ]", text, count=1, flags=re.S)


def operators(source, name):
    text = source.replace(WEAPON_BASE, name)
    for turret in ("tourelle3", "tourelle4"):
        at = text.find("OperatorId = '%s'" % turret)
        start = text.rfind("TCosmeticTurretOperatorDesc", 0, at)
        end = matching(text, text.index("(", start))
        while text[end] in " \t\r\n,":
            end += 1
        text = text[:start] + text[end:]
    return text


def build_weapons():
    path = os.path.join(GENERATED, "WeaponDescriptor.ndf")
    source = get_object(read(path), "WeaponDescriptor_" + WEAPON_BASE)
    blocks = [weapon_descriptor(source, "TP7_JW_POL", "jw"), weapon_descriptor(source, "TP7_DW_POL", "dw")]
    append(path, blocks)

    path = os.path.join(GENERATED, "Ammunition.ndf")
    text = read(path)
    blocks = []
    for new, a in AMMO.items():
        old = a["copy_of"]
        block = fresh_guids(get_object(text, old).replace(old, new), new)
        block = set_field(block, "Name", "'%s'" % a["name"])
        fields = {"Caliber": "'%s'" % a["caliber"],
                  "PorteeMaximale": "((%d) * Metre)" % round(a["range_m"] * 5),  # the game shows a fifth
                  "TempsEntreDeuxTirs": float(a["seconds_between_shots"]),
                  "TempsEntreDeuxSalves": float(a["seconds_between_salvos"]),
                  "NbTirParSalves": a["shots_per_salvo"],
                  "AffichageMunitionParSalve": a["rounds_per_salvo"]}
        if "penetration" in a:
            fields["Arme"] = "EArmeType/AP_%d" % a["penetration"]
        if a["shots_per_salvo"] == 1:
            # Single-shot guns: the firing effect follows the shot (machine guns keep their tracer rate).
            fields["TempsEntreDeuxFx"] = float(a["seconds_between_shots"])
        for key, value in fields.items():
            block = set_field(block, key, value)
        for modifier, key in (("Idling", "accuracy"), ("Moving", "accuracy_moving")):
            block, count = re.subn(r"(\(EBaseHitValueModifier/%s,\s*)[-\d.]+" % modifier,
                                   lambda m: m.group(1) + str(float(a[key])), block)
            if count != 1:
                raise KeyError("%s accuracy in %s" % (modifier, new))
        blocks.append(block)
    append(path, blocks)

    path = os.path.join(GENERATED, "GeneratedDepictionUnitOperatorBlock.ndf")
    source = get_object(read(path), "Operators_" + WEAPON_BASE)
    append(path, [operators(source, n) for n in VARIANTS])

    path = os.path.join(GENERATED, "GeneratedDepictionUnitWeaponBlock.ndf")
    text = read(path)
    weapon = {n: get_object(text, "Weapon_%s_weapon%d_slot1" % (WEAPON_BASE, n)) for n in (1, 2, 3)}
    blocks = [weapon[n].replace(WEAPON_BASE, "TP7_JW_POL") for n in (1, 2, 3)]
    blocks.append("Weapons_TP7_JW_POL is MAP\r\n[\r\n"
                  "    ( [ 'weapon_effet_tag1', 'tir', '1' ], Weapon_TP7_JW_POL_weapon1_slot1 ),\r\n"
                  "    ( [ 'weapon_effet_tag2', 'tir', '1' ], Weapon_TP7_JW_POL_weapon2_slot1 ),\r\n"
                  "    ( [ 'weapon_effet_tag3', 'tir_c', '1' ], Weapon_TP7_JW_POL_weapon3_slot1 ),\r\n]")
    mg = weapon[3].replace(WEAPON_BASE, "TP7_DW_POL").replace("weapon3_slot1", "weapon2_slot1")
    first = mg.replace("weapon2_slot1", "weapon1_slot1").replace("Fx_tourelle2_tir_01", "Fx_tourelle1_tir_01").replace("TurretIndexAsString = '2'", "TurretIndexAsString = '1'")
    blocks += [first, mg]
    blocks.append("Weapons_TP7_DW_POL is MAP\r\n[\r\n"
                  "    ( [ 'weapon_effet_tag1', 'tir_c', '1' ], Weapon_TP7_DW_POL_weapon1_slot1 ),\r\n"
                  "    ( [ 'weapon_effet_tag2', 'tir_c', '1' ], Weapon_TP7_DW_POL_weapon2_slot1 ),\r\n]")
    append(path, blocks)


def build_models():
    folder = path_of("Gfx", "Units", "POL", "Char")
    model_path = os.path.join(folder, WEAPON_BASE + ".ndf")
    depiction_path = os.path.join(folder, WEAPON_BASE + "_Depiction.ndf")
    depiction = get_object(read(depiction_path), "Gfx_" + WEAPON_BASE)
    models, depictions = [], []
    for name, info in VARIANTS.items():
        stem = info["model"]
        models.append("export ModelFile_%s is 'GameData:Assets\\3D\\Units\\POL\\Char\\%s\\%s.Ase2NdfBin'" % (name, stem, stem))
        for suffix, file_name in (("", "ModelFile_" + name), ("_MID", "'GameData:Assets\\3D\\Units\\POL\\Char\\%s\\%s_MID.Ase2NdfBin'" % (stem, stem)),
                                  ("_LOW", "'GameData:Assets\\3D\\Units\\POL\\Char\\%s\\%s_LOW.Ase2NdfBin'" % (stem, stem))):
            models.append("Modele_%s%s is TResourceMultiMaterialMeshWithLod\r\n(\r\n    FileName = %s\r\n    CivMask =  CivMask/MeshModding\r\n"
                          "    TypeMask = TypeMask/Char\r\n)" % (name, suffix, file_name))
        block = depiction.replace(WEAPON_BASE, name)
        if name == "TP7_DW_POL":
            block = block.replace("DepictionOperator_TurretRecoil(TurretNum='1')", "DepictionOperator_TurretRecoilLightMachineGun(TurretNum='1')")
        depictions.append(block)
    append(model_path, models)
    append(depiction_path, depictions)


def patch_unit(text, info):
    for side in ("Front", "Sides", "Rear"):
        text = set_field(text, "ArmorDescriptor" + side, "ArmorDescriptor_Blindage_%d" % info["armor_" + side.lower()])
    text = set_field(text, "ArmorDescriptorTop", "ArmorDescriptor_" + info["armor_top"])
    text = set_field(text, "MaxDamages", str(float(info["strength"])))
    if "concealment" in info:
        text = set_field(text, "UnitConcealmentBonus", str(float(info["concealment"])))
    # The game shows half of Maxspeed in km/h, and the road speed as that times (1 + SpeedBonusOnRoad).
    speed = "((%d) * Metre)" % round(info["speed_kmh"] * 2)
    text = set_field(text, "Maxspeed", speed)
    text = set_field(text, "VitesseCombat", speed)
    text = set_field(text, "SpeedBonusOnRoad", str(round(info["road_speed_kmh"] / info["speed_kmh"] - 1, 4)))
    text = set_field(text, "ProductionYear", info["year"])
    text = set_field(text, "ProductionPrice", info["price"])
    text = set_field(text, "NameInMenuToken", "'%s'" % info["name"])
    text = set_field(text, "AliasName", '"%s"' % info["alias"])
    text = set_field(text, "MenuIconForInterface", "~/Texture_RTS_H_Stuart_M3A3")
    return text.replace('"Char_Moyen"', '"Char_Leger"').replace("OnProduction_Char_Moyen", "OnProduction_Char_Leger")


def patch_texture(block, name, stem):
    """Point the card images at our own files in AssetsModding."""
    match = re.search(r"Texture_(Bouton_Unit|Visual)_" + name + r"(_\w+)?\s+is", block)
    if not match:
        return block
    kind = "Button" if match.group(1) == "Bouton_Unit" else "Visual"
    file_name = "%s_%s.png" % (stem, kind)
    head = re.match(r"(?:export\s+)?\w+\s+is", block).group(0)
    # This template is visible from the Gfx files, unlike TUIResourceTextureWithUsefulnessMaskModded.
    return "%s TUIResourceTexture_CommonModded\r\n(\r\n    FileName = '%s'\r\n)" % (head, file_name)


def build_units():
    objects = [
        os.path.join(GENERATED, "ActionDescriptor.ndf"), os.path.join(GENERATED, "ShowRoomUnits.ndf"),
        os.path.join(GENERATED, "UniteCadavreDescriptor.ndf"), os.path.join(GENERATED, "UniteDescriptor.ndf"),
        path_of("UI", "Resources", "Generated_CubeActionsUnites.ndf"),
        path_of("Unit", "TagUnit.ndf"),
    ]
    # Units resolve textures in $/GFX/Everything, which does not see new objects added to the
    # UI texture files. LabelDescripors.ndf is loaded with the units and already holds textures.
    texture_files = [
        path_of("UI", "Resources", "Textures", "Generated", "ButtonTexturesUnites.ndf"),
        path_of("UI", "Resources", "Textures", "Generated", "TopViewTextures.ndf"),
        path_of("UI", "Resources", "Textures", "Generated", "VisualTextures.ndf"),
    ]
    own = re.compile(r"^(?!WeaponDescriptor_|Weapon_|Weapons_|Operators_|Gfx_|Modele|ModelFile)\w*" + UNIT_BASE + r"(_\w+)?$")
    for path in objects:
        text = read(path)
        found = [text[start:end] for name, start, end in statements(text) if own.match(name)]
        if not found:
            raise RuntimeError("No %s objects in %s" % (UNIT_BASE, path))
        blocks = []
        for name, info in VARIANTS.items():
            for block in found:
                clone = fresh_guids(block.replace(UNIT_BASE, name), name)
                if "TModularUnitDescriptor" in clone[:160] and "Descriptor_Unit_" in clone[:80]:
                    clone = patch_unit(clone, info)
                if path.endswith("Generated_CubeActionsUnites.ndf"):
                    clone = clone.replace("~/Texture_Bouton_Unit_" + name, "$/GFX/Everything/Texture_Bouton_Unit_" + name)
                blocks.append(clone)
        append(path, blocks)

    textures = []
    for path in texture_files:
        text = read(path)
        found = [text[start:end] for name, start, end in statements(text) if own.match(name)]
        if not found:
            raise RuntimeError("No %s textures in %s" % (UNIT_BASE, path))
        for name, info in VARIANTS.items():
            for block in found:
                # Only the object name changes, so the top view keeps pointing at an existing image.
                head, body = block.split(" is ", 1)
                textures.append(patch_texture(head.replace(UNIT_BASE, name) + " is " + body, name, info["model"]))
    append(os.path.join(GAMEPLAY, "Gfx", "LabelDescripors.ndf"), textures)

    for path in (os.path.join(GENERATED, "AllUnits.ndf"), os.path.join(GENERATED, "DependencyHelper.ndf"),
                 os.path.join(GENERATED, "ShowRoomEquivalence.ndf"), path_of("Skirmish", "Generated", "UnitToUnitTag.ndf")):
        lines = read(path).split("\n")
        out = []
        pattern = re.compile(r"\b\w*" + UNIT_BASE + r"\b")
        for line in lines:
            out.append(line)
            if pattern.search(line):
                for name in VARIANTS:
                    out.append(line.replace(UNIT_BASE, name))
        write(path, "\n".join(out))


def build_division():
    packs_path = path_of("Decks", "Generated", "Packs.ndf")
    blocks = []
    for name, unit, phase, experience, count, _ in PACKS:
        entry = "        TDeckTransporterAndUnitsDescriptor\r\n        (\r\n            UnitDescriptorList =\r\n            [\r\n                ~/Descriptor_Unit_%s,\r\n            ]\r\n        ),\r\n" % unit
        blocks.append("export %s is TDeckPackDescriptor\r\n(\r\n    DescriptorId = GUID:{%s}\r\n    PackToken = ''\r\n    AvailableFromPhase = %d\r\n"
                      "    ExperienceLevel = %d\r\n    FactoryType = EDefaultFactories/Tank\r\n    TransporterAndUnitsList =\r\n    [\r\n%s    ]\r\n)"
                      % (name, new_guid("pack", name), phase, experience, entry * count))
    append(packs_path, blocks)

    path = path_of("Decks", "Generated", "Divisions.ndf")
    block = fresh_guids(get_object(read(path), DIVISION_BASE).replace(DIVISION_BASE, DIVISION), DIVISION)
    block = set_field(block, "DivisionName", "'TP7DivName'")
    block = set_field(block, "DivisionNickname", "'TP7DivNick'")
    block = set_field(block, "DivisionDescription", "'TP7DivDesc'")
    for kind, letter in (("Portrait", "P"), ("Type", "T"), ("Description", "D")):
        for part in ("Title", "Body", "Extended"):
            block = set_field(block, "%sHint%sToken" % (kind, part), "'TP7Div%s%s'" % (letter, part[0]))
    block = set_field(block, "EmblemTexture", "~/Texture_Division_Emblem_TP7")
    block = set_field(block, "PortraitTexture", "~/Texture_Division_Portrait_TP7")
    append(path_of("UI", "Resources", "Textures", "Generated", "DivisionTextures.ndf"), [
        "export Texture_Division_Emblem_TP7 is TUIResourceTexture_CommonModded\r\n(\r\n    FileName = 'TP7_Div_Emblem.png'\r\n)",
        "export Texture_Division_Portrait_TP7 is TUIResourceTexture_CommonModded\r\n(\r\n    FileName = 'TP7_Div_Portrait.png'\r\n)",
    ])
    entries = "".join("        (~/%s, %d),\r\n" % (name, cards) for name, _, _, _, _, cards in PACKS)
    block, count = re.subn(r"(PackList\s*=\s*MAP\s*\[\s*?\r?\n)", lambda m: m.group(1) + entries, block, count=1)
    if not count:
        raise RuntimeError("PackList not found")
    append(path, [block])

    path = path_of("Decks", "Generated", "DivisionList.ndf")
    text = read(path)
    needle = "~/%s," % DIVISION_BASE
    if needle not in text:
        raise RuntimeError("Division list entry not found")
    write(path, text.replace(needle, needle + "\r\n        ~/%s," % DIVISION, 1))

    path = path_of("Decks", "Generated", "DeckSerializer.ndf")
    text = read(path)
    division_ids = [int(v) for v in re.findall(r"\(Descriptor_Deck_Division_\w+,\s*(\d+)\)", text)]
    pack_ids = [int(v) for v in re.findall(r"\(Descriptor_Deck_Pack_\w+,\s*(\d+)\)", text)]
    division_id, pack_id = max(division_ids) + 1, max(pack_ids) + 1
    if division_id >= 1 << 10 or pack_id + len(PACKS) >= 1 << 18:
        raise RuntimeError("No free serializer ids")
    line = re.search(r"\(%s,\s*\d+\),?" % DIVISION_BASE, text).group(0)
    text = text.replace(line, line + "\r\n        (%s, %d)," % (DIVISION, division_id), 1)
    line = re.search(r"\(Descriptor_Deck_Pack_POL_1Pc_StuartV_MULTI,\s*\d+\),?", text).group(0)
    added = "".join("\r\n        (%s, %d)," % (pack[0], pack_id + i) for i, pack in enumerate(PACKS))
    write(path, text.replace(line, line + added, 1))
    print("serializer ids: division", division_id, "packs", pack_id, "-", pack_id + len(PACKS) - 1)


def build_texts():
    path = os.path.join(DATA, "Localisation", "MODDING.csv")
    with open(path, "rb") as handle:
        text = handle.read().decode("utf-8").rstrip("\r\n") + "\r\n"
    for token, value in TEXTS.items():
        if len(token) > 10:
            raise ValueError("Token too long: " + token)
        text += '"%s";"";"";;"%s";"";""\r\n' % (token, value)
    # The game's own localisation files are UTF-8 and contain Polish letters.
