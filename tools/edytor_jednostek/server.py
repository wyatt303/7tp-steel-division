"""Edytor jednostek: a small local web editor for the texts and prices of our units in a mod.

  python server.py [mod folder] [port]

Opens http://127.0.0.1:8744/ . Run it with Blender's bundled Python, nothing else is needed:

  & 'C:\\Program Files\\Blender Foundation\\Blender 5.3\\5.3\\python\\bin\\python.exe' -I tools\\edytor_jednostek\\server.py

What it edits, in the mod folder:
  - every text of GameData/Localisation/MODDING.csv (unit, weapon and battlegroup names and
    descriptions),
  - ProductionPrice of each of our units in Gameplay/Gfx/Generated/UniteDescriptor.ndf.
Our units are the ones create_battlegroup.py appended after its marker. Every save first copies
the files it changes to build/mod_backup/edytor_<date_time> in the 7TP project. "Generuj mod" runs
GenerateMod.bat, which the game needs before it sees any change.

The preview reads the rest (speed, armour, weapons, pictures) from the same files. It only listens
on 127.0.0.1.
"""

import csv
import datetime
import io
import json
import os
import re
import shutil
import subprocess
import sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(os.path.dirname(HERE))
DEFAULT_MOD = r"C:\Program Files (x86)\Steam\steamapps\common\Steel Division\Mods\Mod_7TP_Battlegroup"
MOD = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_MOD
PORT = int(sys.argv[2]) if len(sys.argv) > 2 else 8744
GAMEPLAY = os.path.join(MOD, "GameData", "Gameplay")
GENERATED = os.path.join(GAMEPLAY, "Gfx", "Generated")
CSV_PATH = os.path.join(MOD, "GameData", "Localisation", "MODDING.csv")
UNITS_PATH = os.path.join(GENERATED, "UniteDescriptor.ndf")
WEAPONS_PATH = os.path.join(GENERATED, "WeaponDescriptor.ndf")
AMMO_PATH = os.path.join(GENERATED, "Ammunition.ndf")
TEXTURE_FILES = [os.path.join(GAMEPLAY, "Gfx", "LabelDescripors.ndf"),
                 os.path.join(GAMEPLAY, "UI", "Resources", "Textures", "Generated", "WeaponTextures.ndf")]
ASSETS = os.path.join(MOD, "AssetsModding")
MARKER = "// 7TP mod: generated by create_battlegroup.py"
STATEMENT = re.compile(r"(?m)^(?:export\s+|private\s+)?(\w+)\s+is\b")
_cache = {}


def read_text(path):
    """NDF files are Latin-1 in the mod; cached by modification time because they are large."""
    stamp = os.path.getmtime(path)
    hit = _cache.get(path)
    if hit and hit[0] == stamp:
        return hit[1]
    with open(path, "rb") as handle:
        text = handle.read().decode("latin-1")
    _cache[path] = (stamp, text)
    return text


def blocks_after_marker(text, prefix):
    """{name: block} for statements named prefix* that the generator appended after its marker."""
    start = text.find(MARKER)
    if start < 0:
        return {}
    starts = [(m.start(), m.group(1)) for m in STATEMENT.finditer(text, start)]
    out = {}
    for k, (pos, name) in enumerate(starts):
        if name.startswith(prefix):
            end = starts[k + 1][0] if k + 1 < len(starts) else len(text)
            out[name] = text[pos:end]
    return out


def block_named(text, name):
    match = re.search(r"(?m)^(?:export\s+)?" + re.escape(name) + r"\s+is\b", text)
    if not match:
        return ""
    nxt = STATEMENT.search(text, match.end())
    return text[match.start():nxt.start() if nxt else len(text)]


def field(block, key):
    match = re.search(r"(?m)^\s*" + key + r"\s*=\s*(.+?)\s*$", block)
    return match.group(1) if match else None


def number(value):
    match = re.search(r"-?\d+(?:\.\d+)?", value or "")
    return float(match.group(0)) if match else None


def read_csv():
    with open(CSV_PATH, "rb") as handle:
        raw = handle.read().decode("utf-8")
    rows = list(csv.reader(io.StringIO(raw), delimiter=";", quotechar='"'))
    return rows


def write_csv(rows):
    """Write in the generator's layout: every field quoted except the empty CONSTRAINT column."""
    lines = []
    for row in rows:
        if not row:
            continue
        cells = []
        for i, cell in enumerate(row):
            if i == 3 and cell in ("", "CONSTRAINT"):
                cells.append(cell)
            else:
                cells.append('"%s"' % cell.replace('"', '""'))
        lines.append(";".join(cells))
    return ("\r\n".join(lines) + "\r\n").encode("utf-8")


def texture_files():
    """Texture object name -> our PNG in AssetsModding (only CommonModded ones we added)."""
    out = {}
    for path in TEXTURE_FILES:
        if not os.path.exists(path):
            continue
        for m in re.finditer(r"(?:export\s+)?(\w+)\s+is\s+TUIResourceTexture_CommonModded\s*\(\s*FileName\s*=\s*'([^']+)'",
                             read_text(path)):
            out[m.group(1)] = m.group(2)
    return out


def unit_data():
    texts = {row[0]: row[4] for row in read_csv()[1:] if len(row) > 4}
    pictures = texture_files()
    units_text = read_text(UNITS_PATH)
    weapons_text = read_text(WEAPONS_PATH)
    ammo_text = read_text(AMMO_PATH)
    units = []
    for name, block in blocks_after_marker(units_text, "Descriptor_Unit_").items():
        unit = name[len("Descriptor_Unit_"):]
        token = (field(block, "NameInMenuToken") or "").strip("'")
        speed = number(field(block, "Maxspeed"))
        bonus = number(field(block, "SpeedBonusOnRoad")) or 0.0
        armor = {}
        for side in ("Front", "Sides", "Rear", "Top"):
            value = (field(block, "ArmorDescriptor" + side) or "").replace("ArmorDescriptor_", "")
            armor[side] = value
        icon = (field(block, "TextureForInterface") or "").split("/")[-1]
        weapons = []
        manager = block_named(weapons_text, "WeaponDescriptor_" + unit)
        seen = []
        for ammo_name in re.findall(r"Ammunition\s*=\s*~/(\w+)", manager):
            seen.append(ammo_name)
        for ammo_name in dict.fromkeys(seen):
            ammo = block_named(ammo_text, ammo_name)
            arme = field(ammo, "Arme") or ""
            ap = re.search(r"AP_(\d+)", arme)
            texture = (field(ammo, "InterfaceWeaponTexture") or "").split("/")[-1]
            weapons.append({
                "ammo": ammo_name,
                "count": seen.count(ammo_name),
                "token": (field(ammo, "Name") or "").strip("'"),
                "caliber": (field(ammo, "Caliber") or "").strip("'").replace("_", "."),
                "kind": (field(ammo, "TypeArme") or "").strip("'"),
                "ap": int(ap.group(1)) if ap else None,
                "range_m": round(number(field(ammo, "PorteeMaximale")) / 5) if number(field(ammo, "PorteeMaximale")) else None,
                "salvo": number(field(ammo, "NbTirParSalves")),
                "picture": pictures.get(texture),
            })
        stem = None
        for texture_name, file_name in pictures.items():
            if texture_name == "Texture_Visual_" + unit:
                stem = file_name
        units.append({
            "unit": unit,
            "token": token,
            "name": texts.get(token, ""),
            "alias": (field(block, "AliasName") or "").strip('"'),
            "price": int(number(field(block, "ProductionPrice")) or 0),
            "year": int(number(field(block, "ProductionYear")) or 0),
            "speed_kmh": round(speed / 2) if speed else None,
            "road_kmh": round(speed / 2 * (1 + bonus)) if speed else None,
            "max_damage": number(field(block, "MaxDamages")),
            "armor": armor,
            "weapons": weapons,
            "pictures": {
                "visual": stem,
                "button": pictures.get(icon),
                "top": pictures.get("Texture_TopView_" + unit),
                "rts": pictures.get("Texture_RTS_" + unit),
            },
        })
    return units


def state():
    rows = read_csv()
    header, body = rows[0], [r for r in rows[1:] if r]
    return {
        "mod": MOD,
        "texts": [{"token": r[0], "text": r[4] if len(r) > 4 else ""} for r in body],
        "units": unit_data(),
        "header": header,
    }


def backup(paths):
    folder = os.path.join(PROJECT, "build", "mod_backup", "edytor_" + datetime.datetime.now().strftime("%Y-%m-%d_%H%M%S"))
    for path in paths:
        target = os.path.join(folder, os.path.relpath(path, MOD))
        os.makedirs(os.path.dirname(target), exist_ok=True)
        shutil.copy2(path, target)
    return folder


def save(payload):
    texts = payload.get("texts", {})
    prices = payload.get("prices", {})
    problems = []
    for token, text in texts.items():
        if "\n" in text or "\r" in text:
            problems.append("%s: tekst nie może mieć nowych linii" % token)
        if '"' in text:
            problems.append("%s: tekst nie może mieć cudzysłowu \"" % token)
    for unit, price in prices.items():
        if not isinstance(price, int) or not 0 <= price <= 1000:
            problems.append("%s: cena musi być liczbą od 0 do 1000" % unit)
    if problems:
        return {"ok": False, "problems": problems}

    rows = read_csv()
    changed_rows = 0
    for row in rows[1:]:
        if row and row[0] in texts and len(row) > 4 and row[4] != texts[row[0]]:
            row[4] = texts[row[0]]
            changed_rows += 1
    units_text = read_text(UNITS_PATH)
    new_units = units_text
    ours = blocks_after_marker(units_text, "Descriptor_Unit_")
    changed_prices = 0
    for unit, price in prices.items():
        name = "Descriptor_Unit_" + unit
        if name not in ours:
            return {"ok": False, "problems": ["Nieznana jednostka " + unit]}
        block = ours[name]
        patched, count = re.subn(r"(?m)^(\s*ProductionPrice\s*=\s*)\d+", lambda m: m.group(1) + str(price), block)
        if count != 1:
            return {"ok": False, "problems": ["Nie znaleziono ceny w " + unit]}
        if patched != block:
            new_units = new_units.replace(block, patched, 1)
            changed_prices += 1

    touched = []
    if changed_rows:
        touched.append(CSV_PATH)
    if new_units != units_text:
        touched.append(UNITS_PATH)
    if not touched:
        return {"ok": True, "message": "Nic się nie zmieniło."}
    folder = backup(touched)
    if changed_rows:
        with open(CSV_PATH, "wb") as handle:
            handle.write(write_csv(rows))
    if new_units != units_text:
        with open(UNITS_PATH, "wb") as handle:
            handle.write(new_units.encode("latin-1"))
    return {"ok": True, "message": "Zapisano: %d napisów, %d cen. Kopia: %s. Teraz wygeneruj mod." % (
        changed_rows, changed_prices, folder)}


def game_running():
    result = subprocess.run(["tasklist", "/FI", "IMAGENAME eq SteelDivision.exe"], capture_output=True, text=True)
    return "SteelDivision.exe" in result.stdout


def generate():
    if game_running():
        return {"ok": False, "problems": ["Gra jest uruchomiona. Zamknij ją przed generowaniem moda."]}
    result = subprocess.run(["cmd", "/c", r".\GenerateMod.bat"], cwd=MOD, capture_output=True, text=True,
                            stdin=subprocess.DEVNULL, timeout=900)
    tail = "\n".join((result.stdout + result.stderr).splitlines()[-8:])
    if result.returncode != 0:
        return {"ok": False, "problems": ["GenerateMod.bat zakończył się kodem %d." % result.returncode, tail]}
    return {"ok": True, "message": "Mod wygenerowany. Uruchom grę od nowa.", "log": tail}


class Handler(BaseHTTPRequestHandler):
    def send(self, code, body, kind):
        self.send_response(code)
        self.send_header("Content-Type", kind)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def send_json(self, data, code=200):
        self.send(code, json.dumps(data, ensure_ascii=False).encode("utf-8"), "application/json; charset=utf-8")

    def do_GET(self):
        if self.path in ("/", "/index.html"):
            with open(os.path.join(HERE, "index.html"), "rb") as handle:
                return self.send(200, handle.read(), "text/html; charset=utf-8")
        if self.path == "/api/state":
            try:
                return self.send_json(state())
            except Exception as error:  # shown in the page
                return self.send_json({"error": str(error)}, 500)
        if self.path.startswith("/assets/"):
            name = os.path.basename(self.path[len("/assets/"):])
            path = os.path.join(ASSETS, name)
            if name.lower().endswith(".png") and os.path.isfile(path):
                with open(path, "rb") as handle:
                    return self.send(200, handle.read(), "image/png")
        self.send(404, b"not found", "text/plain")

    def do_POST(self):
        length = int(self.headers.get("Content-Length", "0"))
        payload = json.loads(self.rfile.read(length) or b"{}")
        try:
            if self.path == "/api/save":
                return self.send_json(save(payload))
            if self.path == "/api/generate":
                return self.send_json(generate())
        except Exception as error:
            return self.send_json({"ok": False, "problems": [str(error)]}, 500)
        self.send(404, b"not found", "text/plain")

    def log_message(self, *args):
        pass


if __name__ == "__main__":
    if not os.path.isfile(CSV_PATH):
        sys.exit("Nie znaleziono %s" % CSV_PATH)
    print("Edytor jednostek: http://127.0.0.1:%d/  (mod: %s)" % (PORT, MOD))
    ThreadingHTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
